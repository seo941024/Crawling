def clean(name):
    text = re.sub(r"/\s*\d{2}년\s*\d{1,2}월\s*\d{1,2}일", " ", name)  # 유통기한 표기
    text = text.replace("맛밤", "군밤견과").replace("쇼콜라", "초콜릿")  # 맛 제거와 부분 일치 오류를 피하려고 먼저 바꾼다
    text = re.sub(r"\S+\s맛(?![가-힣])", " ", text)  # "간장 맛"처럼 떨어진 맛 표현("맛도락", "맛있는"은 제외)
    text = re.sub(r"\S*맛", " ", text)               # "녹차맛" 같은 맛 표현은 종류가 아니라 향이다
    return re.sub(r"\s+", "", text).lower()


def categorize(name, source_category="", site=""):
    if _key(name) in MANUAL:
        return MANUAL[_key(name)]
    text = clean(name)
    best_cat, best_pos = None, -1
    for cat, words in RULES:
        for w in words:
            pos = text.rfind(w)
            if pos > best_pos:  # 상품명에서 더 뒤쪽에 있는 키워드의 분류를 우선 (위치가 같으면 먼저 정한 분류 유지)
                best_cat, best_pos = cat, pos
    if best_cat:
        return best_cat
    if GENERIC_SNACK in text:
        return "과자·스낵"
    return SOURCE_FALLBACK.get(source_category, SITE_FALLBACK.get(site, "기타"))
